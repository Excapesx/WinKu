// Android is the visual authority. Rebuild desktop tokens and marks from its sources.
import { readFile, writeFile } from "node:fs/promises";
const root = new URL("../", import.meta.url);
const android = new URL("../android/app/src/main/", root);
const read = (path) => readFile(new URL(path, android), "utf8");
const colors = await read(
  "java/io/github/jackwener/dsh/core/designsystem/Color.kt",
);
const accent = colors.match(/val Brand = Color\(0xFF([0-9A-F]{6})\)/)[1];
function palette(name) {
  const section = colors.split(`val ${name} = DshColors(`)[1].split("\n)")[0];
  const result = { business: `#${accent.toLowerCase()}` };
  for (const [, key, hex] of section.matchAll(
    /(\w+) = Color\(0x([0-9A-F]{8})\)/g,
  ))
    result[key] =
      `#${hex.slice(2)}${hex.startsWith("FF") ? "" : hex.slice(0, 2)}`.toLowerCase();
  return result;
}
const roles = {
  background: "bgBase",
  surface: "bgLayer1",
  foreground: "labelPrimary",
  muted: "labelSecondary",
  sidebar: "sidebar",
  "sidebar-active": "sidebarActive",
  bubble: "bubble",
  composer: "inputMajor",
  selector: "selector",
  border: "borderL2",
  hover: "hover",
  "hover-solid": "hoverSolid",
  primary: "link",
  brand: "business",
  accent: "business",
  "action-fill": "brandPrimary",
  "on-action": "labelOnPrimary",
  "disabled-fill": "buttonPrimaryDimmed",
  soft: "businessTertiary",
  error: "error",
  success: "success",
  code: "inlineCode",
};
const css = [
  "/* Generated by scripts/sync-android-design.mjs from Android Color.kt. */",
];
for (const [name, selector] of [
  ["LightDsh", ":root"],
  ["DarkDsh", ':root[data-theme="dark"]'],
]) {
  const values = palette(name);
  css.push(
    `${selector} {\n${Object.entries(roles)
      .map(([role, key]) => {
        if (!values[key]) throw Error(`Missing Android color: ${key}`);
        return `  --${role}: ${values[key]};`;
      })
      .join("\n")}\n}`,
  );
  // Native LearningWebView supplies these same overrides to the shared renderer.
  css.push(
    `${selector} .learning-content {\n  --surface: ${values.bgBase};\n  --foreground: ${values.labelPrimary};\n  --muted: ${values.labelSecondary};\n  --primary: ${values.business};\n  --border: ${values.borderL2};\n  --soft: ${name === "LightDsh" ? "#e3f3ea" : "#143024"};\n  --code: ${name === "LightDsh" ? "#f4f4f7" : "#141417"};\n  --radius: 20px;\n}`,
  );
}
await writeFile(new URL("src/android-design.css", root), css.join("\n") + "\n");
const xml = await read("res/drawable/brand_mark.xml");
const mark = {
  viewBox: "0 0 100 100",
  path: xml.match(/android:pathData="([^"]+)"/)[1],
  strokeWidth: Number(xml.match(/android:strokeWidth="([^"]+)"/)[1]),
};
await writeFile(
  new URL("src/android-brand.ts", root),
  `// Generated from Android res/drawable/brand_mark.xml.\nexport const androidMark = ${JSON.stringify(mark, null, 2)} as const;\n`,
);
const launcher = await read("res/drawable/ic_launcher_fg.xml");
const background = (await read("res/values/colors.xml")).match(
  /name="launcher_bg">#FF([0-9A-F]{6})</i,
)[1];
const path = launcher.match(/android:pathData="([^"]+)"/)[1];
const strokeWidth = launcher.match(/android:strokeWidth="([^"]+)"/)[1];
await writeFile(
  new URL("app-icon.svg", root),
  `<svg xmlns="http://www.w3.org/2000/svg" width="512" height="512" viewBox="0 0 108 108"><rect width="108" height="108" rx="24" fill="#${background.toLowerCase()}"/><path d="${path}" fill="none" stroke="#${accent.toLowerCase()}" stroke-width="${strokeWidth}" stroke-linecap="round" stroke-linejoin="round"/></svg>\n`,
);
