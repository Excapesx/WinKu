def esc(s):
    s = s.replace('&', '&amp;').replace('<', '&lt;').replace('>', '&gt;').replace("'", "\\'").replace('"', '\\"')
    if s.startswith(' ') or s.endswith(' ') or s == '': s = '"' + s + '"'
    if s.startswith('@') or s.startswith('?'): s = '\\' + s
    return s
